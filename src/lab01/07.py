N = input('Зашифрованная строка: ')

First = ''
Second = ''

Fp, Sp = 0, 0

for n in range(len(N) - 1):

    if N[n].isupper() and First == '':
        First = N[n]
        Fp = n

    if N[n] in '1234567890' and N[n+1] not in '1234567890' and Second == '':
        Second = N[n+1]
        Sp = n + 1

Interval = Sp - Fp

result = ''

for n in range(Fp, len(N), Interval):
    result += N[n]

print(result)


























































